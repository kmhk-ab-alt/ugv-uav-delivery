import assert from 'node:assert/strict';
import fs from 'node:fs';
import {focusJob,updateStory} from '../showcase/story.js';
const html=fs.readFileSync(new URL('../showcase/index.html',import.meta.url),'utf8');
const nodes=new Map([...html.matchAll(/id="([^"]+)"/g)].map(m=>[m[1],{textContent:'',className:'',hidden:false,src:null,getAttribute(){return this.src;}}]));
globalThis.document={getElementById(id){assert(nodes.has(id),`Missing DOM element: ${id}`);return nodes.get(id);}};
const s={packages:{a:{name:'a',phase:'to_transfer',mode:'relay'},b:{name:'b',phase:'handoff',mode:'relay'}},site_perception:{mode:'fixture',pending:true,sites:{pickup_A:{available:false,reason:'closed'},pickup_B:{available:true,reason:'open'}},frames:{pickup_A:'data:image/jpeg;base64,test'}}};
assert.equal(focusJob(s,'a').name,'a');updateStory(s);
assert.match(nodes.get('vision-label').textContent,/VLM未使用/);
assert.match(nodes.get('label-pickup_A').textContent,/確認中/);
s.site_perception.pending=false;s.site_perception.mode='vlm';updateStory(s);
assert.match(nodes.get('vision-label').textContent,/実カメラ/);
assert.match(nodes.get('label-pickup_A').textContent,/通行不可/);
assert.match(nodes.get('label-pickup_B').textContent,/通行可/);
s.packages.a.receipt_confirmed=true;assert.equal(focusJob(s,'a').name,'b');
s.site_perception.error='timeout';updateStory(s);assert.match(nodes.get('vision-status').textContent,/エラー/);
const viewer=fs.readFileSync(new URL('../showcase/viewer.js',import.meta.url),'utf8');
for(const m of viewer.matchAll(/\$\('([^']+)'\)/g))assert(nodes.has(m[1]),`Viewer refers to removed element: ${m[1]}`);
console.log('Focus, perception display, and viewer DOM references passed');
